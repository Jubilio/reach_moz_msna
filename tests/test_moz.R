source('R-scripts/moz/helpers.R')
s <- data.frame(type=c('integer','text','text'),name=c('age','other_a','other_b'),scope='Submissions',check.names=FALSE)
s[['label::english']] <- c('Age','Other','Other')
ch <- data.frame(list_name='l',name=c('20','25'),check.names=FALSE)
ch[['label::english']] <- c('20 litres','25 litres')
m <- map_headers(c('Age','Other','_index','unseen'), 'Submissions', s, ch)
stopifnot(m$variable[1]=='age', m$status[2]=='ambiguous',m$status[3]=='metadata',m$status[4]=='unmapped')
stopifnot(decode_multiple('20 litres 25 litres', ch)=='20;25')
stopifnot(is.na(decode_multiple('unknown',ch)))
amb <- data.frame(name=c('a','b','c'),check.names=FALSE)
amb[['label::english']] <- c('one two','one','two')
stopifnot(is.na(decode_multiple('one two',amb)))
d <- data.frame(.record_key='5', value='raw',uuid='household')
f <- data.frame(dataset='Submissions',record_key='5',variable='value',old_value='raw',new_value='fixed',action='replace',approved='yes',reviewer='reviewer',reason='verified')
a <- apply_feedback(list(Submissions=d),f)
stopifnot(a$data$Submissions$value=='fixed',nrow(a$applied)==1)
f$old_value <- 'stale'
stopifnot(inherits(try(apply_feedback(list(Submissions=d),f),silent=TRUE),'try-error'))
f$variable <- 'uuid';f$old_value <- 'household'
stopifnot(inherits(try(apply_feedback(list(Submissions=d),f),silent=TRUE),'try-error'))
stopifnot(inherits(try(record_keys(data.frame(`_index`=c('1','1'),check.names=FALSE)),silent=TRUE),'try-error'))
cat('Mozambique helper tests passed.\n')
